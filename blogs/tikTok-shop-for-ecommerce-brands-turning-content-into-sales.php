                    <h3 class="sub-heading">Content And Commerce Work Together</h3>
                    <p class="sub-text mb-4">
                        Traditional ecommerce often begins with a customer searching for something.
                    </p>
                    <p class="sub-text mb-4">
                        TikTok can work differently. A customer may see a product while watching unrelated content and become interested because the presentation catches their attention.
                    </p>
                    <p class="sub-text mb-4">
